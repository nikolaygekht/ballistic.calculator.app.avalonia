"""Build claude/video/youtube-metadata.md — everything to paste into YouTube, per video — from demo-script.md
(titles, channel/playlist/episode descriptions, the common end block) plus the chapters and tags below.
Usage: python make_metadata.py"""
import pathlib, re

VIDEO = pathlib.Path(__file__).resolve().parent.parent
src = (VIDEO / "demo-script.md").read_text(encoding="utf-8")
meta = src[src.index("## YouTube metadata"):]


def para(label):
    """The paragraph after a bold label, up to the next blank line + bold label / heading / code fence."""
    i = meta.index(label) + len(label)
    m = re.search(r"\n\n(?=\*\*|#|```|Per-episode|Every description)", meta[i:])
    return " ".join(meta[i:i + m.start()].split()).strip()


def block_after(label):
    i = meta.index(label); j = meta.index("```", i) + 3; k = meta.index("```", j)
    return meta[j:k].strip("\n")


titles = {int(m.group(1)): m.group(0)[len(m.group(1)) + 2:].strip()
          for m in re.finditer(r"^(\d+)\. .+$", block_after("Per-episode titles"), re.M)}
END = block_after("Every description ends with the same block")
channel = meta[meta.index("**Channel description**"):meta.index("**Playlist title:**")]
channel = channel.split(":\n", 1)[1].strip()
_cp = channel.split("\n\n")
channel = "\n\n".join([" ".join(_cp[0].split())] + _cp[1:])        # one line per paragraph, links one per line
desc = {1: para("**Episode 1 description** (the series overview lives here, not in the narration):")}
eps = meta[meta.index("### Episode descriptions"):]
for m in re.finditer(r"\*\*Episode (\d+)\.\*\* (.*?)(?=\n\n\*\*Episode \d+\.\*\*|\Z)", eps, re.S):
    paras = [" ".join(p.split()) for p in m.group(2).strip().split("\n\n")]
    desc[int(m.group(1))] = "\n\n".join(paras)

CHAPTERS = {
    1: "0:00 Intro|0:22 A new trajectory|0:49 The load|1:22 The ammunition library|1:51 Rifle, zero, range|3:05 The result",
    2: "0:00 Intro|0:40 Imperial|1:57 Summary, reticle|3:03 Save it",
    3: "0:00 Intro|0:46 Weather|1:46 Wind",
    4: "0:00 Intro|0:38 Spin drift|1:33 Aerodynamic jump|2:24 Coriolis",
    5: "0:00 Intro|0:36 Dialled clicks|1:54 A winter zero in July",
    6: "0:00 Intro|0:34 What a BC really is|1:45 Where drag curves come from|2:46 A trajectory on the radar curve|4:26 Compare the two|5:33 Save it",
    7: "0:00 Intro|0:15 Recap: the radar file|0:53 Spin drift|1:17 Coriolis|1:39 July air, February zero|2:11 Wind and aerodynamic jump|2:54 The scope: Far and Near BDC|3:29 A target in the scope|3:46 A real BDC reticle: Trijicon V-COG|4:23 Reticle editor and the AI skill",
    8: "0:00 Intro|0:53 The supersonic load|2:08 Its sight picture|2:30 The subsonic load, zeroed with the other|3:37 What a shared zero costs|4:00 The reticle for the subsonic load",
    9: "0:00 Intro|0:28 On the flat|0:42 Two kinds of drop on the chart|1:07 Uphill|2:26 Downhill|2:42 The rifleman's rule",
    10: "0:00 Intro|0:40 From several ballistic coefficients|1:54 Checking it against the radar curve|2:44 From measured velocities|3:29 The air of the range|4:33 Checking it against Warner's BC|5:08 Wrap-up",
}
COMMON_TAGS = ["ballistic calculator", "Ballistic Calculator 2", "long range shooting", "external ballistics",
               "bullet drop", "open source", "ballistics software"]
TAGS = {
    1: ["trajectory", "ammunition library", "how to"],
    2: ["ballistic table", "mil-dot", "range card"],
    3: ["wind drift", "density altitude", "weather"],
    4: ["spin drift", "aerodynamic jump", "Coriolis effect"],
    5: ["scope clicks", "zero", "temperature"],
    6: ["ballistic coefficient", "G7", "G1", "Doppler radar", "drag curve", "Lapua Scenar-L"],
    7: ["BDC reticle", "Trijicon VCOG", "reticle editor"],
    8: ["300 Blackout", "subsonic", "suppressor", "Trijicon VCOG"],
    9: ["shooting uphill", "shooting downhill", "angle shooting", "rifleman's rule"],
    10: ["drag table", "custom drag curve", "ballistic coefficient", "Doppler radar", "Warner Flatline", ".338"],
}

out = ["# YouTube metadata — ready to paste",
       "",
       "Generated by `build/make_metadata.py` from `demo-script.md` (## YouTube metadata) — edit there, then re-run.",
       "Upload private, check, then publish (see `youtube.md`).",
       "",
       "## Channel description", "", "```", channel, "```", "",
       "## Playlist", "", f"**Title:** {para('**Playlist title:**')}", "", "```", para("**Playlist description:**"), "```", ""]
for n in sorted(titles):
    tags = COMMON_TAGS + TAGS[n]
    out += [f"## Episode {n}", "", f"**Title:** {titles[n]}", "", "**Description:**", "", "```",
            desc[n], "", "Chapters:", *CHAPTERS[n].split("|"), "", END, "```", "",
            f"**Tags** ({len(', '.join(tags))} characters, limit 500): {', '.join(tags)}", ""]
# The 30 s ad (claude/video/ad30/): 16:9 is the channel's first video, 9:16 a Short.
PLAYLIST = "https://www.youtube.com/playlist?list=PLLcWDVvDdkbU"
AD_BODY = ("Ballistic Calculator 2: a free, open-source external ballistics calculator for Windows, Linux and macOS.\n\n"
           "Trajectory tables and charts, load comparison, your own drag tables (from radar data, several BCs or measured "
           "velocities), a reticle view with BDC holds, and a Monte Carlo hit-probability estimate. It is a full point-mass "
           "model of the flight, but still a model: check it against your own shots.\n\n"
           "Every number in this video was computed by the program's own engine.")
AD_TAGS = COMMON_TAGS + ["Monte Carlo", "hit probability", "drag table", "BDC reticle", "Coriolis effect", "spin drift"]
ADS = [
    ("Ad 16:9", "Ballistic Calculator 2 — free, open-source external ballistics in 30 seconds",
     AD_BODY + "\n\n" + END.replace("Playlist:", "Full tutorial series:")),
    ("Short", "Wind, drag, spin, Coriolis — one free ballistic calculator",
     AD_BODY + "\n\nDownload: https://github.com/nikolaygekht/ballistic.calculator.app.avalonia/releases\n"
     "User guide: https://nikolaygekht.github.io/ballistic.calculator.app.avalonia\n"
     f"Full tutorial series: {PLAYLIST}\n\n#ballistics #longrange #opensource"),
]
for head, title, body in ADS:
    out += [f"## {head}", "", f"**Title:** {title}", "", "**Description:**", "", "```", body, "```", "",
            f"**Tags** ({len(', '.join(AD_TAGS))} characters, limit 500): {', '.join(AD_TAGS)}", ""]
(VIDEO / "youtube-metadata.md").write_text("\n".join(out), encoding="utf-8")
missing = [n for n in titles if n not in desc]
print("episodes:", sorted(titles), "missing descriptions:", missing)
